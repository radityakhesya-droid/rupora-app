function generateSeries(base: number, points: number, volatility: number, drift = 0): number[] {
  const arr: number[] = [];
  let current = base * (1 - drift * 0.4);
  for (let i = 0; i < points; i++) {
    const wave = Math.sin(i * 0.45) * volatility * 0.4;
    const step = ((i % 3 === 0 ? 1 : -0.7) * volatility * 0.35) + wave + (base * drift) / points;
    current = Math.max(10, current + step);
    arr.push(Math.round(current));
  }
  arr[arr.length - 1] = base;
  return arr;
}

function buildHistory(base: number, vol: number): Record<string, number[]> {
  return {
    '1D': generateSeries(base, 24, vol * 0.35, 0.01),
    '1W': generateSeries(base, 28, vol * 0.7, 0.025),
    '1M': generateSeries(base, 30, vol * 1.2, 0.04),
    '3M': generateSeries(base, 36, vol * 2.1, 0.08),
    '6M': generateSeries(base, 40, vol * 3.0, 0.12),
    '1Y': generateSeries(base, 48, vol * 4.5, 0.18),
    'ALL': generateSeries(base, 54, vol * 6.5, 0.35),
  };
}

